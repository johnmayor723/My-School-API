/**
 * Bulk-seeds PUBLISHED AdmissionRule documents for every active
 * InstitutionProgramme offering, so the matching engine actually has
 * something to evaluate against. Without this, the Draft->Review->Approved->
 * Published workflow and the matching engine are both fully built but sit on
 * an almost-empty AdmissionRule collection.
 *
 * Each rule's O'Level/UTME subject requirements come from the offering
 * programme's subjectProfile (see apply-subject-profiles.js). Its UTME
 * minimum-score cutoff comes from one of two sources, in priority order:
 *
 *  1. CourseTierCutoff (see src/models/CourseTierCutoff.js) — a curated real
 *     cutoff an admin entered for this programme at the institution's tier
 *     (see INSTITUTION_TIERS in config/constants.js), e.g. "Medicine at a
 *     Tier 1 Federal university = 250". One entry covers every institution
 *     in that tier at once.
 *  2. The formula fallback — offering institution's AND programme's own
 *     metadata.competitivenessIndex (see apply-competitiveness-tiers.js and
 *     apply-course-tiers.js) blended via COMPETITIVENESS_BLEND_WEIGHTS. Used
 *     only where no CourseTierCutoff entry exists yet for that pair.
 *
 * Neither source is institution-verified data — both carry the same
 * "best-effort, not authoritative" caveat, recorded plainly in each
 * generated rule's source/verification fields so it reads as a starting
 * point, not a confirmed requirement.
 *
 * The moment an admin publishes a rule with the real institution-published
 * cutoff (via the normal DRAFT->REVIEW->APPROVED->PUBLISHED admin workflow),
 * that number IS the matching engine's key factor — evaluateUtmeScore reads
 * whatever sits in utme.minimumScore regardless of its origin. This script
 * must never clobber that. A rule only counts as "still auto-generated" if
 * it carries one of this script's own source markers AND has never been
 * verified (verification.lastVerifiedAt unset); any such rule gets its
 * minimumScore (and source) recomputed on re-run. Every other rule —
 * anything an admin created, edited, or marked verified — is left
 * completely untouched.
 *
 * Usage: node scripts/rules/generate-admission-rules.js [--dry-run] [--session="2026/2027"]
 */

const { connectDb, disconnectDb } = require("../../src/config/db");
const { Institution, InstitutionProgramme, Programme, AdmissionSession, AdmissionRule, CourseTierCutoff } = require("../../src/models");
const logger = require("../../src/config/logger");
const { RULE_STATUS, RULE_SOURCE_TYPE, RECORD_STATUS, COMPETITIVENESS_BLEND_WEIGHTS } = require("../../src/config/constants");
const {
  FORMULA_SOURCE_TITLE,
  MATRIX_SOURCE_TITLE,
  isStillAutoGenerated,
  nearestInstitutionTier,
} = require("../../src/utils/cutoffCoverage");

const DRY_RUN = process.argv.includes("--dry-run");
const SESSION_ARG = process.argv.find((a) => a.startsWith("--session="))?.split("=")[1];

const FORMULA_NOTE =
  "Auto-generated from a general JAMB subject-combination pattern by course category/tier and the institution's " +
  "competitiveness tier. Not institution-verified — review and replace with the university's actual published " +
  "requirements when available.";
const MATRIX_NOTE =
  "Cutoff taken from the course-tier cutoff matrix for this programme and institution tier. Curated, not " +
  "institution-verified — review and replace with the university's actual published requirements when available.";

// Institution and course competitiveness are different axes (see
// apply-competitiveness-tiers.js and apply-course-tiers.js); course tier is
// weighted higher so e.g. Medicine at a Tier 2 institution still outranks a
// Tier 3 course at a Tier 1 institution. Missing data on either side falls
// back to a mid-tier 0.45 rather than penalising or inventing certainty.
function utmeCutoffFor(institutionIndex, courseIndex) {
  const inst = typeof institutionIndex === "number" ? institutionIndex : 0.45;
  const course = typeof courseIndex === "number" ? courseIndex : 0.45;
  const combined = COMPETITIVENESS_BLEND_WEIGHTS.course * course + COMPETITIVENESS_BLEND_WEIGHTS.institution * inst;
  // 0 -> 120, 1 -> 230, rounded to the nearest 5 to read like a real JAMB cutoff.
  return Math.round((120 + combined * 110) / 5) * 5;
}

async function resolveSession() {
  if (SESSION_ARG) {
    const named = await AdmissionSession.findOne({ name: SESSION_ARG });
    if (!named) throw new Error(`No admission session named "${SESSION_ARG}"`);
    return named;
  }
  const candidates = await AdmissionSession.find({ isActive: true });
  const real = candidates.filter((s) => !/test/i.test(s.name));
  if (real.length === 1) return real[0];
  if (real.length === 0 && candidates.length > 0) return candidates[0];
  throw new Error(
    `Ambiguous admission session (${candidates.length} active) — pass --session="2026/2027" to pick one explicitly.`
  );
}

function buildRuleDoc({ offering, programme, sessionId, minimumScore, sourceTitle, note, now }) {
  const profile = programme.subjectProfile || {};
  const olevelSubjects = profile.olevelRequiredSubjects?.length ? profile.olevelRequiredSubjects : ["English Language", "Mathematics"];
  const utmeSubjects = profile.utmeRequiredSubjects?.length ? profile.utmeRequiredSubjects : ["English Language"];

  return {
    institution: offering.institution,
    programme: offering.programme,
    admissionSession: sessionId,
    status: RULE_STATUS.PUBLISHED,
    utme: {
      minimumScore,
      requiredSubjects: utmeSubjects,
      subjectCombinations: [utmeSubjects],
    },
    olevel: {
      minimumCredits: profile.olevelMinimumCredits || 5,
      requiredSubjects: olevelSubjects,
      minimumGrade: "C6",
      acceptedExaminations: ["WAEC", "NECO"],
      sittingsAllowed: 2,
    },
    additional: { postUtmeRequired: true },
    source: {
      title: sourceTitle,
      type: RULE_SOURCE_TYPE.OTHER,
      sourceDate: now,
    },
    verification: { notes: note },
    reviewNotes: note,
    submittedForReviewAt: now,
    reviewedAt: now,
    approvedAt: now,
    publishedAt: now,
  };
}

function cutoffFor(institution, programme, matrixByKey) {
  const tier = nearestInstitutionTier(institution.metadata?.competitivenessIndex);
  const matrixEntry = tier === null ? undefined : matrixByKey.get(`${programme._id}:${tier}`);
  if (matrixEntry) {
    return { minimumScore: matrixEntry.cutoffMark, sourceTitle: MATRIX_SOURCE_TITLE, note: MATRIX_NOTE };
  }
  const minimumScore = utmeCutoffFor(institution.metadata?.competitivenessIndex, programme.metadata?.competitivenessIndex);
  return { minimumScore, sourceTitle: FORMULA_SOURCE_TITLE, note: FORMULA_NOTE };
}

async function run() {
  await connectDb();
  logger.info(`Generating admission rules${DRY_RUN ? " (dry run)" : ""}`);

  const session = await resolveSession();
  logger.info(`Target admission session: ${session.name} (${session._id})`);

  const [offerings, institutions, programmes, existingRules, matrixRows] = await Promise.all([
    InstitutionProgramme.find({ status: RECORD_STATUS.ACTIVE }).lean(),
    Institution.find({}, { name: 1, metadata: 1 }).lean(),
    Programme.find({}, { name: 1, subjectProfile: 1, metadata: 1 }).lean(),
    AdmissionRule.find(
      { admissionSession: session._id, status: RULE_STATUS.PUBLISHED },
      { institution: 1, programme: 1, "utme.minimumScore": 1, source: 1, verification: 1 }
    ).lean(),
    CourseTierCutoff.find({}, { programme: 1, institutionTier: 1, cutoffMark: 1 }).lean(),
  ]);

  const institutionById = new Map(institutions.map((i) => [String(i._id), i]));
  const programmeById = new Map(programmes.map((p) => [String(p._id), p]));
  const existingByKey = new Map(existingRules.map((r) => [`${r.institution}:${r.programme}`, r]));
  const matrixByKey = new Map(matrixRows.map((m) => [`${m.programme}:${m.institutionTier}`, m]));

  logger.info(`Loaded ${matrixRows.length} course-tier cutoff matrix entries`);

  const now = new Date();
  const newDocs = [];
  const updates = [];
  let skippedMissingRef = 0;
  let skippedVerifiedOrManual = 0;
  let unchanged = 0;
  let fromMatrix = 0;
  let fromFormula = 0;

  for (const offering of offerings) {
    const key = `${offering.institution}:${offering.programme}`;
    const institution = institutionById.get(String(offering.institution));
    const programme = programmeById.get(String(offering.programme));
    if (!institution || !programme) {
      skippedMissingRef += 1;
      continue;
    }

    const { minimumScore, sourceTitle, note } = cutoffFor(institution, programme, matrixByKey);
    if (sourceTitle === MATRIX_SOURCE_TITLE) fromMatrix += 1;
    else fromFormula += 1;
    const existing = existingByKey.get(key);

    if (!existing) {
      newDocs.push(buildRuleDoc({ offering, programme, sessionId: session._id, minimumScore, sourceTitle, note, now }));
      continue;
    }

    if (!isStillAutoGenerated(existing)) {
      skippedVerifiedOrManual += 1;
      continue;
    }

    if (existing.utme?.minimumScore === minimumScore && existing.source?.title === sourceTitle) {
      unchanged += 1;
      continue;
    }

    updates.push({ _id: existing._id, minimumScore, sourceTitle, note });
  }

  logger.info(
    `Prepared ${newDocs.length} new rules, ${updates.length} cutoff updates to still-auto-generated rules ` +
      `(${unchanged} unchanged, ${skippedVerifiedOrManual} admin-verified/manual rules left untouched, ` +
      `${skippedMissingRef} with a missing institution/programme reference) — ` +
      `${fromMatrix} offerings priced from the cutoff matrix, ${fromFormula} from the formula fallback`
  );

  if (!DRY_RUN) {
    if (newDocs.length > 0) {
      const BATCH = 2000;
      let inserted = 0;
      for (let i = 0; i < newDocs.length; i += BATCH) {
        const batch = newDocs.slice(i, i + BATCH);
        const res = await AdmissionRule.insertMany(batch, { ordered: false });
        inserted += res.length;
        logger.info(`  inserted ${inserted}/${newDocs.length}`);
      }
    }
    if (updates.length > 0) {
      const BATCH = 500;
      let updated = 0;
      for (let i = 0; i < updates.length; i += BATCH) {
        const batch = updates.slice(i, i + BATCH);
        await AdmissionRule.bulkWrite(
          batch.map(({ _id, minimumScore, sourceTitle, note }) => ({
            updateOne: {
              filter: { _id },
              update: {
                $set: {
                  "utme.minimumScore": minimumScore,
                  "source.title": sourceTitle,
                  "verification.notes": note,
                  reviewNotes: note,
                },
              },
            },
          })),
          { ordered: false }
        );
        updated += batch.length;
        logger.info(`  updated ${updated}/${updates.length}`);
      }
    }
  }

  logger.info("Rule generation complete", {
    created: DRY_RUN ? 0 : newDocs.length,
    updated: DRY_RUN ? 0 : updates.length,
    dryRun: DRY_RUN,
  });
  await disconnectDb();
}

run().catch((err) => {
  logger.error("Rule generation failed", { error: err.message, stack: err.stack });
  process.exitCode = 1;
});
